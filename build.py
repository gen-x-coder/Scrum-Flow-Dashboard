"""Build the readable standalone Radix script; Python standard library only."""
from pathlib import Path
import re
import argparse

ROOT = Path(__file__).resolve().parent
MODULES = ['history-cache.js', 'jira-api.js', 'metrics.js', 'workflow.js', 'charts.js', 'manual.js', 'advice.js', 'app.js']

def section(name):
    return '\n;\n// ===== ' + name + ' =====\n' + (ROOT / name).read_text(encoding='utf-8') + '\n;\n'

def once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'Loader changed: expected exactly one {old!r}')
    return source.replace(old, new)

def read_version(loader=None):
    if loader is None:
        loader = (ROOT / 'dashboard.js').read_text(encoding='utf-8')
    match = re.search(r"window\.RADIX_VERSION\s*=\s*'([^']+)'", loader)
    if not match or not re.fullmatch(r'\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?', match.group(1)):
        raise ValueError('Missing or invalid RADIX_VERSION')
    return match.group(1)

def build(output, expected_version=None):
    loader = (ROOT / 'dashboard.js').read_text(encoding='utf-8')
    version = read_version(loader)
    if expected_version and expected_version != version:
        raise ValueError(f'Tag version {expected_version} differs from loader version {version}')
    loader = once(loader, '/\\/dashboard\\.js(?:[?#]|$)/', '/\\/radix\\.js(?:[?#]|$)/')
    loader = once(loader, 'await load(\'configuration.js\');', section('configuration.js'))
    chain = ' '.join(f"await load('{name}');" for name in MODULES)
    loader = once(loader, chain, ''.join(section(name) for name in MODULES) + '\n// Expose the two lexical bindings used by inline UI handlers.\nwindow.RadixHistory = RadixHistory;\nwindow.l_hide = l_hide;\n')
    # Only the optional organization config is loaded externally. Preserve api, not attachment-version parameters.
    loader = once(loader, "el.src = new URL(name,base).href + '?v=' + encodeURIComponent(optional ? Date.now() : version);", "const url = new URL(name,base);\n    const api = new URL(script.src).searchParams.get('api');\n    if (api !== null) url.searchParams.set('api',api);\n    url.searchParams.set('v',String(optional ? Date.now() : version));\n    el.src = url.href;")
    license_text = (ROOT / 'LICENSE').read_text(encoding='utf-8')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('/*! Radix '+version+' | generated by build.py\n'+license_text.replace('*/','* /')+'\n*/\n'+loader, encoding='utf-8')
    print(f'Built {output} ({version}, {output.stat().st_size} bytes)')

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'dist'/'radix.js')
    parser.add_argument('--version', help='Require this version in dashboard.js')
    parser.add_argument('--print-version', action='store_true', help='Print the version without building')
    args=parser.parse_args()
    if args.print_version:
        print(read_version())
    else:
        build(args.output, args.version)
